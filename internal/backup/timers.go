package backup

import (
	"context"
	"fmt"
	"os"

	"github.com/r3p-dev/dermaga/internal/databases"
	"github.com/r3p-dev/dermaga/internal/name"
	"github.com/r3p-dev/dermaga/internal/quadlet"
)

func binaryPath() string {
	exe, err := os.Executable()
	if err == nil && exe != "" {
		return exe
	}
	return "/usr/local/bin/" + name.Name
}

// FailureServiceUnit returns the name and content of the failure notification service.
func FailureServiceUnit() (string, []byte) {
	unitName := name.Unit + "backup-failed@.service"
	content := fmt.Sprintf(`# Generated by %[1]s. Don't edit directly.
[Unit]
Description=%[1]s backup failure notification for %%i

[Service]
Type=oneshot
ExecStart=%[2]s backup failure-notify %%i
`, name.Name, binaryPath())
	return unitName, []byte(content)
}

// InstallFailureUnit writes dg-backup-failed@.service to user systemd directory.
func (m *Manager) InstallFailureUnit(ctx context.Context) error {
	fn, data := FailureServiceUnit()
	if err := m.Host.WriteUserUnit(fn, data); err != nil {
		return fmt.Errorf("writing %s: %w", fn, err)
	}
	return m.Host.ReloadSystemd(ctx)
}

// InstallDBTimer generates, writes, and enables dg-backup-db-<name>.timer and service.
func (m *Manager) InstallDBTimer(ctx context.Context, d databases.Database) error {
	bin := binaryPath()
	sched := d.BackupSchedule
	if sched == "" {
		sched = "03:00"
	}

	tm := quadlet.Timer{
		Name:        "backup-db-" + d.Name,
		Description: "backup db:" + d.Name,
		Binary:      bin,
		Args:        []string{"backup", "run", "--scheduled", "db:" + d.Name},
		OnCalendar:  quadlet.FormatCalendar(sched),
		RandomDelay: 1800, // 30m randomized delay (BRIEF §3.8)
		OnFailure:   name.Unit + "backup-failed@%n.service",
	}

	svcData, tmrData, err := tm.Units()
	if err != nil {
		return fmt.Errorf("rendering timer units for db %s: %w", d.Name, err)
	}

	svcName := tm.UnitName() + ".service"
	tmrName := tm.UnitName() + ".timer"

	if err := m.Host.WriteUserUnit(svcName, svcData); err != nil {
		return fmt.Errorf("writing %s: %w", svcName, err)
	}
	if err := m.Host.WriteUserUnit(tmrName, tmrData); err != nil {
		return fmt.Errorf("writing %s: %w", tmrName, err)
	}

	if err := m.Host.ReloadSystemd(ctx); err != nil {
		return fmt.Errorf("reloading systemd: %w", err)
	}

	if err := m.Host.EnableTimer(ctx, tmrName); err != nil {
		return fmt.Errorf("enabling timer %s: %w", tmrName, err)
	}

	return nil
}

// RemoveDBTimer disables and removes the timer and service units for a database.
func (m *Manager) RemoveDBTimer(ctx context.Context, dbName string) error {
	baseName := name.Unit + "backup-db-" + dbName
	tmrName := baseName + ".timer"
	svcName := baseName + ".service"

	_ = m.Host.DisableTimer(ctx, tmrName)
	_ = m.Host.RemoveUserUnit(tmrName)
	_ = m.Host.RemoveUserUnit(svcName)
	return m.Host.ReloadSystemd(ctx)
}

// InstallSystemTimer generates and enables the daily system backup timer.
func (m *Manager) InstallSystemTimer(ctx context.Context, sched string) error {
	if sched == "" {
		sched = "02:00"
	}
	bin := binaryPath()
	tm := quadlet.Timer{
		Name:        "backup-system",
		Description: "backup system",
		Binary:      bin,
		Args:        []string{"backup", "run", "--scheduled", "system"},
		OnCalendar:  quadlet.FormatCalendar(sched),
		RandomDelay: 1800,
		OnFailure:   name.Unit + "backup-failed@%n.service",
	}

	svcData, tmrData, err := tm.Units()
	if err != nil {
		return fmt.Errorf("rendering system timer units: %w", err)
	}

	svcName := tm.UnitName() + ".service"
	tmrName := tm.UnitName() + ".timer"

	if err := m.Host.WriteUserUnit(svcName, svcData); err != nil {
		return fmt.Errorf("writing %s: %w", svcName, err)
	}
	if err := m.Host.WriteUserUnit(tmrName, tmrData); err != nil {
		return fmt.Errorf("writing %s: %w", tmrName, err)
	}

	if err := m.Host.ReloadSystemd(ctx); err != nil {
		return fmt.Errorf("reloading systemd: %w", err)
	}

	return m.Host.EnableTimer(ctx, tmrName)
}

// SyncAllTimers reconciles timers for all existing databases and system backups.
func (m *Manager) SyncAllTimers(ctx context.Context) error {
	_ = m.InstallFailureUnit(ctx)
	_ = m.InstallSystemTimer(ctx, "02:00")

	dbs, err := m.Databases.List(ctx)
	if err != nil {
		return err
	}
	for _, d := range dbs {
		if err := m.InstallDBTimer(ctx, d); err != nil {
			return err
		}
	}
	return nil
}
