// Package quadlet renders the units dermaga owns: Quadlet .container,
// .volume and .network files and systemd .timer/.service pairs, all through
// one strict INI writer (ARCHITECTURE D14), and dry-runs them (D5).
package quadlet

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"
)

type section struct {
	name string
	kv   [][2]string
}

// unit is an ordered list of sections. Keys are generator constants; values
// may carry user input and are checked and escaped by render.
type unit []section

var keyRE = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)

// onFailureRE is the only value written with a live systemd specifier: a
// template instance named after the failing unit, e.g. dg-backup-failed@%n.service.
var onFailureRE = regexp.MustCompile(`^[a-z][a-z0-9-]*@%n\.service$`)

const header = "# Generated by dermaga. Don't edit: change the app with dermaga instead.\n"

// render writes the unit. A value is rejected if it is empty (Key= resets a
// setting in systemd), has control characters (a line break would start a new
// key), surrounding spaces (systemd strips them) or a trailing backslash (line
// continuation). % and $ are doubled: systemd expands specifiers in nearly
// every setting and $VAR in ExecStart, which Quadlet copies most keys into.
// The one exception is OnFailure=, which must match onFailureRE and keeps its
// %n: doubled, systemd rejects the dependency and failures go unreported.
// Quadlet itself passes quotes and backslashes through unchanged.
func (u unit) render() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	for i, s := range u {
		if i > 0 {
			b.WriteByte('\n')
		}
		fmt.Fprintf(&b, "[%s]\n", s.name)
		for _, kv := range s.kv {
			k, v := kv[0], kv[1]
			if !keyRE.MatchString(k) {
				return nil, fmt.Errorf("unit key %q: invalid", k)
			}
			if err := checkValue(v); err != nil {
				return nil, fmt.Errorf("%s=: %w", k, err)
			}
			if k == "OnFailure" {
				if !onFailureRE.MatchString(v) {
					return nil, fmt.Errorf("OnFailure=%q: want <template>@%%n.service", v)
				}
			} else {
				v = strings.ReplaceAll(v, "%", "%%")
				v = strings.ReplaceAll(v, "$", "$$")
			}
			fmt.Fprintf(&b, "%s=%s\n", k, v)
		}
	}
	return b.Bytes(), nil
}

func checkValue(v string) error {
	switch {
	case v == "":
		return fmt.Errorf("empty value")
	case strings.TrimSpace(v) != v:
		return fmt.Errorf("value %q has leading or trailing spaces", v)
	case strings.HasSuffix(v, `\`):
		return fmt.Errorf("value %q ends with a backslash", v)
	}
	for _, r := range v {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("value %q contains a control character", v)
		}
	}
	return nil
}
